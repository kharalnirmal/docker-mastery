const { test } = require('node:test');
const assert = require('node:assert/strict');
const { publicFile } = require('../tools/build.cjs');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { assertRegularInput, assertOwnedOutput } = require('../tools/build.cjs');
test('export validates regular inputs and refuses unowned output before replacement', t => {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'guide-export-'));
  t.after(() => fs.rmSync(base, { recursive: true, force: true }));
  fs.writeFileSync(path.join(base, 'public.txt'), 'public');
  assert.doesNotThrow(() => assertRegularInput(base, 'public.txt'));
  assert.throws(() => assertRegularInput(base, 'missing.txt'));
  assert.throws(() => assertOwnedOutput(base), /ownership marker/);
  fs.writeFileSync(path.join(base, '.docker-mastery-build'), 'wrong owner');
  assert.throws(() => assertOwnedOutput(base), /ownership marker/);
  fs.writeFileSync(path.join(base, '.docker-mastery-build'), 'Generated by tools/build.cjs\n');
  assert.doesNotThrow(() => assertOwnedOutput(base));
  fs.mkdirSync(path.join(base, 'target'));
  fs.writeFileSync(path.join(base, 'target/file.txt'), 'not public');
  fs.symlinkSync(path.join(base, 'target'), path.join(base, 'alias'), process.platform === 'win32' ? 'junction' : 'dir');
  assert.throws(() => assertRegularInput(base, 'alias/file.txt'), /symbolic-link/);
  assert.throws(() => assertOwnedOutput(path.join(base, 'alias')), /ownership marker/);
});
test('export accepts only canonical public paths', () => {
  for (const file of ['README.md.bak.txt', 'assets/../private.txt', 'assets//file.js', 'assets/./file.js', 'assets\\private.txt', '/docs/file.md', 'docs/C:/file', 'docs/RESULTS/data.json', 'docs/archive.tar', 'docs/data.db', 'docs/secret\0.txt']) assert.equal(publicFile(file), false, file);
  for (const file of ['docs/guide.md', 'examples/migrations/initial.sql']) assert.equal(publicFile(file), true, file);
});
test('static release includes public sources but excludes local and sensitive artifacts', () => {
  assert.equal(publicFile('docs/OPERATIONS-RUNBOOK.md'), true);
  assert.equal(publicFile('docs/.env'), false);
  for (const file of ['index.html', 'README.md', 'assets/images/naruto.webp', 'assets/fonts/Inter-OFL.txt', 'examples/compose/prisma/.env.example', 'examples/compose/prisma/.dockerignore', 'examples/delivery/docker-ci.yaml']) assert.equal(publicFile(file), true, file);
  for (const file of ['.git/config', 'tests/results/compose-prisma.json', 'tools/serve.cjs', 'examples/compose/prisma/.env', 'examples/compose/prisma/.env.local', 'examples/compose/prisma/node_modules/a.js', 'examples/compose/prisma/.next/server.js', 'examples/compose/prisma/generated/client.js', 'examples/recovery/backup.dump', 'assets/images/naruto.jpg', 'examples/key.pem']) assert.equal(publicFile(file), false, file);
});
