// Export only version-controlled public inputs; never crawl local lab artifacts.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'dist');
const marker = '.docker-mastery-build';
function publicFile(file) {
  if (typeof file !== 'string' || /[\\:\x00-\x1f\x7f]/.test(file) || file.split('/').some(part => !part || part === '.' || part === '..')) return false;
  if (!/^(?:(?:index\.html|README\.md|NOTICE\.md|CONTENT-REVIEW\.md|LAB-VALIDATION\.md)$|assets\/|examples\/|docs\/)/.test(file)) return false;
  return !file.split('/').some(part =>
    ['node_modules', '.next', 'generated', 'results', '.git'].includes(part.toLowerCase()) ||
    (part.startsWith('.') && !['.env.example', '.dockerignore'].includes(part)) ||
    /\.(?:dump|gz|tgz|zip|tar|pem|key|p12|pfx|log|jpg|bak|sqlite|db)$/i.test(part));
}
function assertRegularInput(base, file) {
  let current = base;
  for (const part of file.split('/')) {
    current = path.join(current, part);
    if (fs.lstatSync(current).isSymbolicLink()) throw new Error(`Refusing symbolic-link input: ${file}`);
  }
  if (!fs.statSync(current).isFile()) throw new Error(`Not a regular export file: ${file}`);
}
function assertOwnedOutput(directory) {
  if (!fs.existsSync(directory)) return;
  const stat = fs.lstatSync(directory);
  const ownership = path.join(directory, marker);
  if (stat.isSymbolicLink() || !stat.isDirectory() || !fs.existsSync(ownership) ||
      !fs.lstatSync(ownership).isFile() || fs.lstatSync(ownership).isSymbolicLink() ||
      fs.readFileSync(ownership, 'utf8') !== 'Generated by tools/build.cjs\n') {
    throw new Error('Refusing to replace dist without the regular build ownership marker.');
  }
}
function build() {
  const files = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8' })
    .split('\0').filter(Boolean).filter(publicFile);
  // Validate every source and output boundary before deleting the previous build.
  for (const file of files) assertRegularInput(root, file);
  assertOwnedOutput(output);
  fs.rmSync(output, { recursive: true, force: true });
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(path.join(output, marker), 'Generated by tools/build.cjs\n');
  let bytes = 0;
  for (const file of files) {
    const source = path.join(root, file);
    const destination = path.join(output, file);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(source, destination);
    bytes += fs.statSync(source).size;
  }
  // Fail before publication if the guide references an asset omitted from export.
  const context = { window: {} };
  for (const script of ['lessons', 'foundations', 'compose', 'recovery', 'delivery', 'visual-guides']) {
    vm.runInNewContext(fs.readFileSync(path.join(output, `assets/js/${script}.js`), 'utf8'), context);
  }
  const pages = [fs.readFileSync(path.join(output, 'index.html'), 'utf8'), ...context.window.LESSONS.map(lesson => lesson.html)];
  for (const markup of pages) {
    for (const [, target] of markup.matchAll(/(?:src|href)="([^"#]+)"/g)) {
      if (/^https?:/.test(target)) continue;
      if (!fs.existsSync(path.join(output, target))) throw new Error(`Missing exported link: ${target}`);
    }
  }
  console.log(`Static release: ${files.length} files, ${(bytes / 1024 / 1024).toFixed(2)} MiB in dist/`);
  return files;
}
module.exports = { publicFile, build, assertRegularInput, assertOwnedOutput };
if (require.main === module) build();
